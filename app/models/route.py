"""
Route models — delivery routes and stops generated by the Nearest Neighbour algorithm.
"""

from datetime import datetime
from app import db


class DeliveryRoute(db.Model):
    """
    A planned delivery route from a warehouse to one or more distribution points.
    The ordered list of stops is produced by the Nearest Neighbour heuristic.
    """

    __tablename__ = "delivery_routes"

    id = db.Column(db.Integer, primary_key=True)
    route_code = db.Column(db.String(20), unique=True, nullable=False)
    name = db.Column(db.String(150), nullable=False)
    origin_warehouse_id = db.Column(
        db.Integer, db.ForeignKey("warehouses.id"), nullable=False
    )
    total_distance_km = db.Column(db.Float, default=0.0)
    estimated_duration_hours = db.Column(db.Float)
    vehicle_type = db.Column(db.String(50))
    status = db.Column(
        db.Enum("draft", "approved", "active", "completed", name="route_status_enum"),
        default="draft",
        nullable=False,
    )
    notes = db.Column(db.Text)
    created_by = db.Column(db.Integer, db.ForeignKey("users.id"), nullable=False)
    created_at = db.Column(db.DateTime, default=datetime.utcnow)

    # Relationships
    stops = db.relationship(
        "RouteStop", back_populates="route", order_by="RouteStop.stop_order", lazy="joined"
    )
    batch = db.relationship("DistributionBatch", back_populates="route", uselist=False)
    origin_warehouse = db.relationship("Warehouse")

    def __repr__(self) -> str:
        return f"<DeliveryRoute {self.route_code} – {self.total_distance_km:.1f} km>"


class RouteStop(db.Model):
    """
    An ordered stop on a delivery route.
    """

    __tablename__ = "route_stops"

    id = db.Column(db.Integer, primary_key=True)
    route_id = db.Column(db.Integer, db.ForeignKey("delivery_routes.id"), nullable=False)
    distribution_point_id = db.Column(
        db.Integer, db.ForeignKey("distribution_points.id"), nullable=False
    )
    stop_order = db.Column(db.Integer, nullable=False, comment="1-based position in route")
    distance_from_prev_km = db.Column(db.Float, default=0.0)
    estimated_beneficiaries = db.Column(db.Integer, default=0)
    notes = db.Column(db.String(255))

    # Relationships
    route = db.relationship("DeliveryRoute", back_populates="stops")
    distribution_point = db.relationship(
        "DistributionPoint", back_populates="route_stops"
    )

    def __repr__(self) -> str:
        return f"<RouteStop order={self.stop_order} route={self.route_id}>"
